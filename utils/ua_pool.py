class UAPool:
    def __init__(self, ua_list=None, rotate="random"):
        self.pool = list(ua_list) if ua_list else list(DEFAULT_UA_POOL)
        self.rotate = rotate
        self._lock = threading.RLock()
        self._idx = 0

    def get(self):
        with self._lock:
            if self.rotate == "random":
                return random.choice(self.pool)
            ua = self.pool[self._idx % len(self.pool)]
            self._idx += 1
            return ua